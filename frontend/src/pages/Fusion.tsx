import { useEffect, useState } from "react";
import { Link, useSearchParams } from "react-router-dom";

type Fusion = {
  name: string; selected_concepts: string[]; common_mechanisms: string[]; combination_logic: string;
  proposed_innovation: string; working_principle: string; implementation_possibilities: string[];
  advantages: string[]; risks_limitations: string[];
};

const Row = ({ label, items }: { label: string; items: string[] }) =>
  items.length ? <div className="mt-2"><b className="text-cyan-300">{label}</b><ul className="list-disc pl-5 text-sm">{items.map((x) => <li key={x}>{x}</li>)}</ul></div> : null;

export default function FusionPage() {
  const [params] = useSearchParams();
  const did = params.get("d");
  const [concepts, setConcepts] = useState<string[]>([]);
  const [picked, setPicked] = useState<string[]>((params.get("c") ?? "").split("|").filter(Boolean));
  const [res, setRes] = useState<{ fusion: Fusion; note: string } | null>(null);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState("");

  useEffect(() => {
    if (!did) return;
    fetch(`/api/graph/${did}`).then((r) => (r.ok ? r.json() : Promise.reject()))
      .then((g) => setConcepts(g.nodes.filter((n: any) => n.kind === "concept").map((n: any) => n.label)))
      .catch(() => setErr("Could not load that discovery."));
  }, [did]);

  async function run() {
    setBusy(true); setErr(""); setRes(null);
    try {
      const r = await fetch("/api/fuse-ideas", { method: "POST", headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ discovery_id: Number(did), concepts: picked }) });
      const b = await r.json();
      if (!r.ok) throw new Error(typeof b.detail === "string" ? b.detail : "Request failed");
      setRes(b);
    } catch (e) { setErr((e as Error).message); } finally { setBusy(false); }
  }
  const toggle = (c: string) => setPicked((p) => (p.includes(c) ? p.filter((x) => x !== c) : [...p, c]));

  if (!did) return <p className="text-slate-400">Open a discovery in <Link className="text-cyan-300 underline" to="/app/connections">Connections</Link> and select concepts to fuse.</p>;
  return (
    <div className="max-w-3xl">
      <h1 className="text-3xl font-bold text-white">Idea Fusion</h1>
      <p className="mt-1 text-slate-400">Pick two or more concepts to combine into a hybrid proposal.</p>
      <div className="mt-4 space-y-2">
        {concepts.map((c) => (
          <label key={c} className="flex items-center gap-2 text-sm">
            <input type="checkbox" checked={picked.includes(c)} onChange={() => toggle(c)} />{c}
          </label>
        ))}
      </div>
      <button onClick={run} disabled={busy || picked.length < 2} className="mt-4 rounded-lg bg-gradient-to-r from-blue-500 to-violet-500 px-5 py-2.5 text-white disabled:opacity-40">
        {busy ? "Fusing…" : `Fuse ${picked.length} concepts`}
      </button>
      {err && <p role="alert" className="mt-3 text-amber-300">{err}</p>}
      {res && (
        <section className="glass mt-6 p-5">
          <p className="text-sm text-slate-400">{res.note || "Generated by Gemini."} Conceptual proposal, not validated.</p>
          <h2 className="mt-2 text-xl font-semibold text-white">{res.fusion.name}</h2>
          <p className="mt-2">{res.fusion.proposed_innovation}</p>
          <p className="mt-2 text-sm"><b className="text-cyan-300">Combination logic: </b>{res.fusion.combination_logic}</p>
          <p className="mt-2 text-sm"><b className="text-cyan-300">Working principle: </b>{res.fusion.working_principle}</p>
          <Row label="Common mechanisms" items={res.fusion.common_mechanisms} />
          <Row label="Implementation possibilities" items={res.fusion.implementation_possibilities} />
          <Row label="Advantages" items={res.fusion.advantages} />
          <Row label="Risks and limitations" items={res.fusion.risks_limitations} />
          <Link to={`/app/connections?d=${did}`} className="mt-4 inline-block text-cyan-300 underline">See it in the knowledge graph</Link>
        </section>
      )}
    </div>
  );
}
