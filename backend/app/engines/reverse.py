"""Reverse innovation: from a discovery to possible applications."""
from pydantic import BaseModel

from app.config import settings
from app.services.llm import LLMError, generate_json

PROMPT = """The user found an interesting discovery or technology: "{d}".
List 4-6 plausible real-world applications in different fields. Be specific and say why each is relevant and what limits it.
These are ideas, not validated claims. Return ONLY JSON:
{{"applications":[{{"field":str,"application":str,"why_relevant":str,"limitations":str}}]}}"""


class _App(BaseModel):
    field: str
    application: str
    why_relevant: str
    limitations: str


class _Out(BaseModel):
    applications: list[_App]


def reverse_search(text: str):
    if not settings.gemini_api_key:
        return [], "offline", "Reverse search needs a live model; set GEMINI_API_KEY. Nothing is invented offline."
    try:
        out = generate_json(PROMPT.format(d=text), lambda d: _Out.model_validate(d))
        return [a.model_dump() for a in out.applications], "gemini", "Ideas generated by AI; not validated."
    except (LLMError, ValueError) as e:
        return [], "offline", f"Gemini unavailable ({e}). Try again shortly."
